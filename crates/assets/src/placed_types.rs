impl PlacedObjectType {
    /// The registered value whose string is `value`.
    #[must_use]
    pub fn from_value(value: &str, mods: ActiveMods) -> Option<Self> {
        Self::registered(mods)
            .into_iter()
            .find(|t| t.value() == value)
    }
}

