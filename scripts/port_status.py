#!/usr/bin/env python3
"""Write docs/PORT-STATUS.md: which decompiled types a Rust file mirrors.

Status: `ported` (some Rust file names the type in `//! Mirrors:`, or in a `Decompile:` mention
until tagged: marked with `*`), `unported`, or `partial` from docs/port-status-overrides.md.
Run: python3 scripts/port_status.py   (reads the decompile's file names only)
"""
import os
import re
import sys
from collections import defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import check_mirrors as cm  # noqa: E402

COLLAPSED = {
    "MoreSlugcats": "DLC: More Slugcats", "Watcher": "DLC: Watcher", "JollyCoop": "DLC: Jolly Co-op",
    "Expedition": "Expedition / Modding", "Modding": "Expedition / Modding",
    "Menu/Remix": "Remix menus", "DevInterface": "Dev tools and platform glue", "Rewired": "Dev tools and platform glue",
    "RewiredConsts": "Dev tools and platform glue", "Stove": "Dev tools and platform glue",
    "Properties": "Dev tools and platform glue",
}


def group_of(ns):
    for prefix, name in COLLAPSED.items():
        if ns == prefix or ns.startswith(prefix + "/"):
            return name, True
    return ("Base game: " + (ns if ns != "(none)" else "root namespace")), False


def overrides():
    out = {}
    path = os.path.join(cm.ROOT, "docs", "port-status-overrides.md")
    if os.path.isfile(path):
        for l in open(path, encoding="utf-8"):
            m = re.match(r"^-\s*`?([\w/]+)`?\s*:\s*partial\s*:\s*(.+)$", l.strip())
            if m:
                out[m.group(1)] = m.group(2).strip()
    return out


def main():
    rows, _ = cm.load()
    rev = defaultdict(list)
    for f, r in rows.items():
        for c in r["cs"]:
            rev[c].append((f, r["kind"]))
    ov = overrides()
    groups = defaultdict(list)
    for d, _, fs in os.walk(cm.DECOMPILE):
        for f in fs:
            if f.endswith(".cs"):
                rel = os.path.relpath(os.path.join(d, f), cm.DECOMPILE)
                ns = os.path.dirname(rel) or "(none)"
                groups[group_of(ns)].append((ns, f[:-3], rel))
    out = ["# Port status", "",
           "Generated by `scripts/port_status.py`; do not edit. A type is `ported` when a Rust file names it in its",
           "`//! Mirrors:` header (`*` = only an older `Decompile:` mention), `unported` otherwise. `partial` comes from",
           "[`port-status-overrides.md`](port-status-overrides.md). Mapping detail: [`MIRRORS.md`](MIRRORS.md).",
           "'Ported' means a Rust file mirrors the type, not that every member is ported.", ""]
    total = defaultdict(int)
    body = []
    for (title, collapsed), items in sorted(groups.items(), key=lambda kv: (kv[0][1], kv[0][0])):
        items.sort(key=lambda t: (t[0], t[1].lower()))
        ported, partial, unported = [], [], []
        for ns, name, rel in items:
            key = name if ns == "(none)" else f"{ns}/{name}"
            hits = rev.get(rel, [])
            if key in ov:
                partial.append((key, ov[key], hits))
            elif hits:
                ported.append((key, hits))
            else:
                unported.append(key)
        total[title] = (len(items), len(ported), len(partial))
        body.append(f"## {title}")
        body.append(f"{len(items)} types: {len(ported)} ported, {len(partial)} partial, {len(unported)} unported.")
        body.append("")
        if collapsed:
            body += [f"<details><summary>Types ({len(items)})</summary>", ""]
        if partial:
            body += ["Partial:", ""] + [f"- `{k}`: {why}" for k, why, _ in partial] + [""]
        if ported:
            body += ["Ported:", "", "| Type | Rust files |", "|---|---|"]
            for k, hits in ported:
                body.append(f"| `{k}` | " + ", ".join(f"`{f}`" + ("*" if kind == "fallback" else "") for f, kind in hits) + " |")
            body.append("")
        if unported:
            body += ["Unported:", "", ", ".join(unported), ""]
        if collapsed:
            body += ["</details>", ""]
    out += ["## Summary", "", "| Group | Types | Ported | Partial |", "|---|---|---|---|"]
    for (title, _), _i in sorted(groups.items(), key=lambda kv: (kv[0][1], kv[0][0])):
        n, p, pa = total[title]
        out.append(f"| {title} | {n} | {p} | {pa} |")
    out.append("")
    with open(os.path.join(cm.ROOT, "docs", "PORT-STATUS.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(out + body) + "\n")
    print(sum(v[0] for v in total.values()), "types;", sum(v[1] for v in total.values()), "ported")


if __name__ == "__main__":
    main()
