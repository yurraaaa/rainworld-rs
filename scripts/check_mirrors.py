#!/usr/bin/env python3
"""Check the `//! Mirrors:` headers of crates/*/src against the decompile and write docs/MIRRORS.md.

Header format: `//! Mirrors: A.cs, HUD/B.cs [(Member, ...)]` or `//! Mirrors: -` (port-only).
A wrapped entry continues on following `//!` lines indented by two or more spaces.
Fallback while tagging is incomplete: `.cs` names in a header that says `Decompile`
(reported separately). Exit status 1 when a named file is missing or ambiguous.

`load()` returns the data for other generators (index_decompile.py, port_status.py).
"""
import os
import re
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DECOMPILE = os.environ.get("RW_DECOMPILE", "/home/yura/.local/share/ilspy/split")
CS_RE = re.compile(r"[\w./]+\.cs\b")


def is_test(path):
    base = os.path.basename(path)
    parts = path.split(os.sep)
    return (base in ("tests.rs", "test.rs") or base.endswith("_tests.rs")
            or base.endswith("_test.rs") or "tests" in parts[:-1])


def source_files():
    out = []
    crates = os.path.join(ROOT, "crates")
    for crate in sorted(os.listdir(crates)):
        for d, _, fs in os.walk(os.path.join(crates, crate, "src")):
            for f in fs:
                if f.endswith(".rs"):
                    p = os.path.relpath(os.path.join(d, f), ROOT)
                    if not is_test(p):
                        out.append(p)
    return sorted(out)


def decompile_index():
    by_name = defaultdict(list)
    for d, _, fs in os.walk(DECOMPILE):
        for f in fs:
            if f.endswith(".cs"):
                by_name[f].append(os.path.relpath(os.path.join(d, f), DECOMPILE))
    return by_name


def header(path):
    lines = []
    with open(os.path.join(ROOT, path), encoding="utf-8") as fh:
        for line in fh:
            s = line.rstrip("\n")
            if s.startswith("//!"):
                lines.append(s[3:])
            elif s.strip() == "" and not lines:
                continue
            else:
                break
    return lines


def parse(lines):
    """Return (mirrors text or None, fallback .cs names)."""
    for i, l in enumerate(lines):
        m = re.match(r"\s*Mirrors:\s*(.*)$", l)
        if m:
            text = m.group(1)
            for nxt in lines[i + 1:]:
                if not re.match(r"\s{2,}\S", nxt):
                    break
                text += " " + nxt.strip()
            return text.strip(), []
    blob = " ".join(l.strip() for l in lines)
    if "Decompile" in blob:
        return None, sorted(set(CS_RE.findall(blob)))
    return None, []


def resolve(name, by_name):
    """Return (decompile paths, error or None)."""
    if "/" in name:
        return ([name], None) if os.path.isfile(os.path.join(DECOMPILE, name)) else ([], "missing")
    cands = [name]
    parts = name[:-3].split(".")
    while len(parts) > 1:  # Parent.Nested.cs -> Parent.cs
        parts = parts[:-1]
        cands.append(".".join(parts) + ".cs")
    for c in cands:
        if c in by_name:
            hits = by_name[c]
            if c in hits:  # the namespace-less file wins; write `Folder/X.cs` for the others
                return [c], None
            return hits, ("ambiguous" if len(hits) > 1 else None)
    return [], "missing"


def load():
    """Return (rows, errors): rows[rust file] = {kind, cs, text}."""
    by_name = decompile_index()
    rows, errors = {}, []
    for f in source_files():
        mirrors, dec = parse(header(f))
        row = {"kind": "unmapped", "cs": [], "text": ""}
        if mirrors is not None:
            row["text"] = mirrors
            if mirrors.startswith("-"):
                row["kind"] = "port-only"
            else:
                row["kind"] = "mirrors"
                names = CS_RE.findall(mirrors)
                if not names:
                    errors.append(f"{f}: Mirrors line names no .cs file: {mirrors!r}")
                for n in names:
                    hits, err = resolve(n, by_name)
                    if err == "missing":
                        errors.append(f"{f}: {n} not in the decompile")
                    elif err == "ambiguous":
                        errors.append(f"{f}: {n} ambiguous: {', '.join(hits)}")
                    row["cs"] += hits
        elif dec:
            row["kind"] = "fallback"
            row["text"] = ", ".join(dec)
            for n in dec:
                hits, err = resolve(n, by_name)
                if not err:
                    row["cs"] += hits
        row["cs"] = sorted(set(row["cs"]))
        rows[f] = row
    return rows, errors


def write_doc(rows, counts):
    out = ["# Rust to C# mirror map", "",
           "Generated by `scripts/check_mirrors.py` (`python3 scripts/check_mirrors.py`); do not edit.",
           "Convention: every `crates/*/src` file (tests excluded) has a module header line",
           "`//! Mirrors: <Type>.cs[, ...] [(Member, ...)]`, or `//! Mirrors: -` for port-only code.",
           "`fallback` rows come from older `Decompile:` mentions and are not yet tagged.", "",
           "## Coverage", "", "| Crate | mirrors | port-only | fallback | unmapped |", "|---|---|---|---|---|"]
    for c in sorted(counts):
        k = counts[c]
        out.append(f"| {c} | {k['mirrors']} | {k['port-only']} | {k['fallback']} | {k['unmapped']} |")
    out += ["", "## Rust file to C# files", "", "| Rust file | Status | C# files |", "|---|---|---|"]
    for f, r in rows.items():
        cs = ", ".join(r["cs"]) if r["cs"] else ("-" if r["kind"] == "port-only" else "")
        out.append(f"| `{f}` | {r['kind']} | {cs} |")
    rev = defaultdict(list)
    for f, r in rows.items():
        for c in r["cs"]:
            rev[c].append((f, r["kind"]))
    out += ["", "## C# file to Rust files", "", "| C# file | Rust files |", "|---|---|"]
    for c in sorted(rev):
        out.append(f"| `{c}` | " + ", ".join(f"`{f}`" + ("*" if k == "fallback" else "") for f, k in rev[c]) + " |")
    out += ["", "`*` = from a `Decompile:` mention, not a `Mirrors:` line."]
    with open(os.path.join(ROOT, "docs", "MIRRORS.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")


def main():
    rows, errors = load()
    counts = defaultdict(lambda: defaultdict(int))
    for f, r in rows.items():
        counts[f.split("/")[1]][r["kind"]] += 1
    write_doc(rows, counts)
    tot = defaultdict(int)
    for c in sorted(counts):
        print(c, dict(counts[c]))
        for k, v in counts[c].items():
            tot[k] += v
    print("total", dict(tot), "files", len(rows))
    if "--list-unmapped" in sys.argv:
        print("\n".join(f for f, r in rows.items() if r["kind"] != "mirrors" and r["kind"] != "port-only"))
    for e in errors:
        print("ERROR", e)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
